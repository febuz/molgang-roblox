/**
 * Data governance registry — single source of truth for every shared data
 * artifact in the virtualpc ecosystem (game JSON, asset registries, wiki
 * terms, DB schemas).
 *
 * Each entry tracks: who owns it (agent name), where it lives (path/URL),
 * what schema it claims to follow, when it was last updated, what license
 * applies, and a free-text lineage note (what produced it / what consumes
 * it).
 *
 * Owned by the Governor agent. Read by the wiki, asset pipeline, and any
 * agent that wants to know "where does this term come from?".
 *
 * Persisted to data/governance.json with the same dirty-flag + 5s save
 * pattern as the task engine.
 */
import * as fs from 'fs';
import * as path from 'path';
import logger from '../../utils/logger';
import { sharedDataPath, ASSET_REGISTRY_PATH, PROJECT_ROOT } from '../../config/paths';

export type GovernanceKind =
  | 'shared-data'      // shared/*.json on the webgame
  | 'asset-registry'   // asset registries (EDS2, repo-local)
  | 'wiki-term'        // a single wiki entry — ties to wiki.json
  | 'schema'           // DB / Kafka schema
  | 'config'           // shared configuration
  | 'license';         // license / attribution record

export interface GovernanceEntry {
  /** Stable id — kebab-case, e.g. "shared-elements-json" */
  id: string;
  /** Human-readable name */
  name: string;
  kind: GovernanceKind;
  /** Owning agent (must be in AGENT_META) */
  owner: string;
  /** Filesystem path or URL — relative to project root for local files */
  source: string;
  /** Optional schema reference (file path or JSON Schema URL) */
  schema?: string;
  /** Free-text lineage: where this came from + who consumes it */
  lineage?: string;
  /** Last-updated ISO timestamp */
  updatedAt: string;
  /** License or attribution string */
  license?: string;
  /** Tags for cross-referencing (e.g. ['chemistry', 'quantum', 'wiki']) */
  tags?: string[];
}

interface GovernanceState {
  entries: GovernanceEntry[];
}

const GOVERNANCE_PATH = path.join(__dirname, '..', '..', '..', 'data', 'governance.json');
let state: GovernanceState = { entries: [] };
let dirty = false;

function ensureLoaded() {
  if (state.entries.length > 0) return;
  if (!fs.existsSync(GOVERNANCE_PATH)) {
    state = { entries: defaultEntries() };
    dirty = true;
    save();
    return;
  }
  try {
    const raw = fs.readFileSync(GOVERNANCE_PATH, 'utf8');
    state = JSON.parse(raw);
    if (!state.entries) state.entries = [];
  } catch (e: any) {
    logger.warn(`governance: failed to load ${GOVERNANCE_PATH}: ${e.message}`);
    state = { entries: defaultEntries() };
    dirty = true;
  }
}

