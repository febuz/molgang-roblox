let saveTimer: NodeJS.Timeout | null = null;
function scheduleSave() {
  if (saveTimer) return;
  saveTimer = setTimeout(() => {
    saveTimer = null;
    save();
  }, 5000);
}

function save() {
  if (!dirty) return;
  try {
    fs.mkdirSync(path.dirname(GOVERNANCE_PATH), { recursive: true });
    fs.writeFileSync(GOVERNANCE_PATH, JSON.stringify(state, null, 2));
    dirty = false;
  } catch (e: any) {
    logger.warn(`governance: save failed: ${e.message}`);
  }
}

export function listEntries(filter?: { kind?: GovernanceKind; owner?: string; tag?: string }): GovernanceEntry[] {
  ensureLoaded();
  let out = [...state.entries];
  if (filter?.kind) out = out.filter(e => e.kind === filter.kind);
  if (filter?.owner) out = out.filter(e => e.owner === filter.owner);
  if (filter?.tag) out = out.filter(e => (e.tags || []).includes(filter.tag!));
  return out.sort((a, b) => a.id.localeCompare(b.id));
}

export function getEntry(id: string): GovernanceEntry | undefined {
  ensureLoaded();
  return state.entries.find(e => e.id === id);
}

export function registerEntry(entry: Omit<GovernanceEntry, 'updatedAt'> & { updatedAt?: string }): GovernanceEntry {
  ensureLoaded();
  const now = new Date().toISOString();
  const next: GovernanceEntry = { ...entry, updatedAt: entry.updatedAt || now };
  const idx = state.entries.findIndex(e => e.id === entry.id);
  if (idx >= 0) state.entries[idx] = next;
  else state.entries.push(next);
  dirty = true;
  scheduleSave();
  return next;
}

export function getLineage(termOrId: string): { entry?: GovernanceEntry; relatedByTag: GovernanceEntry[] } {
  ensureLoaded();
  const entry = state.entries.find(e => e.id === termOrId || e.name.toLowerCase() === termOrId.toLowerCase());
  if (!entry) return { relatedByTag: [] };
  const tags = new Set(entry.tags || []);
  const related = state.entries.filter(e => e.id !== entry.id && (e.tags || []).some(t => tags.has(t)));
  return { entry, relatedByTag: related };
}

export function flushSync() {
  if (dirty) save();
}
